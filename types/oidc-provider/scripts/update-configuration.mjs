#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const START_MARKER = "// BEGIN GENERATED CONFIGURATION OPTION TYPES";
const END_MARKER = "// END GENERATED CONFIGURATION OPTION TYPES";

function fail(message) {
    console.error(`update-configuration: ${message}`);
    process.exit(1);
}

function parseArguments(argv) {
    let check = false;
    const positional = [];

    for (const argument of argv) {
        if (argument === "--check") {
            check = true;
        } else if (argument.startsWith("-")) {
            fail(`unknown option ${JSON.stringify(argument)}`);
        } else {
            positional.push(argument);
        }
    }

    if (positional.length !== 1) {
        fail("usage: node scripts/update-configuration.mjs [--check] <provider-checkout>");
    }

    return { check, providerDirectory: resolve(positional[0]) };
}

function readJson(path, label) {
    try {
        return JSON.parse(readFileSync(path, "utf8"));
    } catch (error) {
        fail(`could not read ${label} at ${path}: ${error.message}`);
    }
}

function majorMinor(version, label) {
    const match = /^(\d+)\.(\d+)(?:\.|$)/.exec(version);
    if (!match) {
        fail(`${label} has an invalid version: ${JSON.stringify(version)}`);
    }
    return `${match[1]}.${match[2]}`;
}

function configurationEntries(payload) {
    const entries = Array.isArray(payload) ? payload : payload?.configuration;
    if (!Array.isArray(entries)) {
        fail("provider configuration metadata must be an array or an object with a configuration array");
    }

    const seen = new Set();
    for (const [index, entry] of entries.entries()) {
        if (!entry || typeof entry !== "object") {
            fail(`provider type metadata entry ${index} must be an object`);
        }
        if (typeof entry.path !== "string" || !/^[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*$/.test(entry.path)) {
            fail(`provider type metadata entry ${index} has an invalid path`);
        }
        if (entry.type !== undefined && (typeof entry.type !== "string" || !entry.type.trim())) {
            fail(`provider configuration metadata entry ${index} has an invalid type`);
        }
        if (seen.has(entry.path)) {
            fail(`provider type metadata contains duplicate path ${JSON.stringify(entry.path)}`);
        }
        seen.add(entry.path);
    }

    return entries;
}

function indentType(type) {
    return type.split("\n").map((line) => {
        const leading = /^ */.exec(line)[0].length;
        return `${" ".repeat(4 + leading * 2)}${line.slice(leading)}`;
    });
}

function generatedRegion(entries) {
    const lines = [
        START_MARKER,
        "// Generated by scripts/update-configuration.mjs from oidc-provider documentation metadata.",
        "// Do not edit this region by hand.",
        "/* eslint-disable @typescript-eslint/no-invalid-void-type */",
        "interface ConfigurationOptionTypes {",
    ];

    const typed = entries
        .filter((entry) => entry.type !== undefined)
        .map(({ path, type }) => ({ path, type: type.replaceAll("\r\n", "\n").trim() }))
        .sort((left, right) => left.path < right.path ? -1 : left.path > right.path ? 1 : 0);

    for (const { path, type } of typed) {
        const [first, ...rest] = indentType(type);
        lines.push(`${first.slice(0, 4)}${JSON.stringify(path)}: ${first.slice(4)}`);
        lines.push(...rest);
        lines[lines.length - 1] += ";";
    }

    lines.push("}", "/* eslint-enable @typescript-eslint/no-invalid-void-type */", END_MARKER);
    return lines.join("\n");
}

function prose(value, label, path, providerSourceBase) {
    if (typeof value !== "string" || !value.trim()) {
        fail(`provider configuration metadata for ${JSON.stringify(path)} has an invalid ${label}`);
    }
    return value
        .replaceAll("\r\n", "\n")
        .trim()
        .replaceAll("*/", "*\\/")
        .replaceAll(/\]\(\/(?!\/)/g, `](${providerSourceBase}/`);
}

function cleanedDefaultWarning(value, path, providerSourceBase) {
    const lines = prose(value, "default warning", path, providerSourceBase).split("\n");
    if (lines[0] === "> [!IMPORTANT]") lines.shift();
    const warning = lines.map((line) => line.replace(/^> ?/, "")).join("\n").trim();
    return `**Important:**\n\n${warning}`;
}

function wrappedMarkdownLines(value, width) {
    const result = [];
    for (const sourceLine of value.split("\n")) {
        if (!sourceLine.trim()) {
            result.push("");
            continue;
        }

        const match = /^(\s*(?:[-*+] |\d+\. |@see )?)(.*)$/.exec(sourceLine);
        const prefix = match[1];
        const continuation = " ".repeat(prefix.length);
        const tokens = match[2].match(/`[^`]*`|\[[^\]]+\]\([^)]+\)|\S+/g) ?? [];
        let line = prefix;

        for (const token of tokens) {
            const separator = line === prefix || /^[,.;:!?)]/.test(token) ? "" : " ";
            if (line.length > prefix.length && line.length + separator.length + token.length > width) {
                result.push(line);
                line = `${continuation}${token}`;
            } else {
                line += `${separator}${token}`;
            }
        }
        result.push(line);
    }
    return result;
}

function generatedDocumentation(entry, indentation, providerSourceBase) {
    const sections = [];

    if (entry.title !== undefined) sections.push(prose(entry.title, "title", entry.path, providerSourceBase));
    if (entry.experimental === true) {
        sections.push("This is an experimental feature.");
    }
    if (entry.defaultWarning !== undefined) {
        sections.push(cleanedDefaultWarning(entry.defaultWarning, entry.path, providerSourceBase));
    }
    if (entry.description !== undefined) {
        sections.push(prose(entry.description, "description", entry.path, providerSourceBase));
    }

    if (entry.placeholders !== undefined) {
        if (!entry.placeholders || typeof entry.placeholders !== "object") {
            fail(`provider configuration metadata for ${JSON.stringify(entry.path)} has invalid placeholders`);
        }
        for (const key of ["mustConfigure", "shouldCustomize"]) {
            const values = entry.placeholders[key];
            if (values !== undefined) {
                if (!Array.isArray(values) || values.some((value) => typeof value !== "string" || !value)) {
                    fail(
                        `provider configuration metadata for ${
                            JSON.stringify(entry.path)
                        } has invalid ${key} placeholders`,
                    );
                }
            }
        }
    }

    if (entry.recommendations !== undefined) {
        if (!Array.isArray(entry.recommendations)) {
            fail(`provider configuration metadata for ${JSON.stringify(entry.path)} has invalid recommendations`);
        }
        for (const recommendation of entry.recommendations) {
            sections.push(
                `**Recommendation:** ${prose(recommendation, "recommendation", entry.path, providerSourceBase)}`,
            );
        }
    }

    if (entry.see !== undefined) {
        if (!Array.isArray(entry.see)) {
            fail(`provider configuration metadata for ${JSON.stringify(entry.path)} has invalid see references`);
        }
        for (const reference of entry.see) {
            sections.push(`@see ${prose(reference, "see reference", entry.path, providerSourceBase)}`);
        }
    }

    const lines = ["/**"];
    const width = Math.max(40, 120 - indentation.length - 3);
    for (const [sectionIndex, section] of sections.entries()) {
        if (sectionIndex) lines.push(" *");
        for (const line of wrappedMarkdownLines(section, width)) lines.push(line ? ` * ${line}` : " *");
    }
    lines.push(" */");
    return lines.map((line) => `${indentation}${line}`).join("\n");
}

function replaceGeneratedDocumentation(source, entries, providerSourceBase) {
    const byPath = new Map(entries.map((entry) => [entry.path, entry]));
    const found = new Map();
    const pattern = /^([ \t]*)\/\/ @configuration-docs ([^\s]+)\r?\n(?:\1\/\*\*[\s\S]*?^\1 \*\/\r?\n)?/gm;
    const updated = source.replace(pattern, (match, indentation, path) => {
        const entry = byPath.get(path);
        if (!entry) {
            fail(`index.d.ts contains an unknown configuration documentation marker for ${JSON.stringify(path)}`);
        }
        found.set(path, (found.get(path) ?? 0) + 1);
        return `${indentation}// @configuration-docs ${path}\n${
            generatedDocumentation(entry, indentation, providerSourceBase)
        }\n`;
    });

    const missing = entries.map((entry) => entry.path).filter((path) => !found.has(path));
    if (missing.length) {
        fail(`index.d.ts is missing configuration documentation markers for: ${missing.join(", ")}`);
    }

    return updated;
}

function replaceGeneratedRegion(source, region) {
    const start = source.indexOf(START_MARKER);
    const end = source.indexOf(END_MARKER);
    if (start === -1 || end === -1 || end < start) {
        fail("index.d.ts does not contain the generated configuration type markers");
    }
    if (
        source.indexOf(START_MARKER, start + START_MARKER.length) !== -1
        || source.indexOf(END_MARKER, end + END_MARKER.length) !== -1
    ) {
        fail("index.d.ts must contain exactly one generated configuration type region");
    }

    return `${source.slice(0, start)}${region}${source.slice(end + END_MARKER.length)}`;
}

function validateTypeReferences(source, entries) {
    const start = source.indexOf(START_MARKER);
    const end = source.indexOf(END_MARKER);
    if (start === -1 || end === -1 || end < start) {
        fail("index.d.ts does not contain the generated configuration type markers");
    }

    const declarationSource = `${source.slice(0, start)}${source.slice(end + END_MARKER.length)}`;
    const typedPaths = new Set(entries.filter((entry) => entry.type !== undefined).map((entry) => entry.path));
    const referencedPaths = new Set();
    const referencePattern = /\bConfigurationOptionTypes\[(?:"([^"]+)"|'([^']+)')\]/g;

    for (const match of declarationSource.matchAll(referencePattern)) {
        const path = match[1] ?? match[2];
        if (!typedPaths.has(path)) {
            fail(`index.d.ts references unknown generated configuration type ${JSON.stringify(path)}`);
        }
        referencedPaths.add(path);
    }

    const unreferenced = [...typedPaths].filter((path) => !referencedPaths.has(path)).sort();
    if (unreferenced.length) {
        fail(`generated configuration types are not referenced by index.d.ts: ${unreferenced.join(", ")}`);
    }
}

function formatDeclaration(source, packageDirectory, declarationPath) {
    const repositoryDirectory = resolve(packageDirectory, "..", "..");
    const executable = resolve(
        repositoryDirectory,
        "node_modules",
        "dprint",
        "bin.js",
    );
    const result = spawnSync(process.execPath, [executable, "fmt", "--stdin", declarationPath], {
        cwd: repositoryDirectory,
        encoding: "utf8",
        input: source,
        maxBuffer: 16 * 1024 * 1024,
    });
    if (result.error) {
        fail(
            `could not run DefinitelyTyped's dprint executable at ${executable}: ${result.error.message}. Install the repository dependencies first`,
        );
    }
    if (result.status !== 0) {
        if (result.stderr) process.stderr.write(result.stderr);
        fail(`dprint exited with status ${result.status}`);
    }
    return result.stdout;
}

const { check, providerDirectory } = parseArguments(process.argv.slice(2));
const packageDirectory = resolve(fileURLToPath(new URL("..", import.meta.url)));
const declarationPath = resolve(packageDirectory, "index.d.ts");
const typesPackage = readJson(resolve(packageDirectory, "package.json"), "@types package.json");
const providerPackage = readJson(resolve(providerDirectory, "package.json"), "provider package.json");

if (typesPackage.name !== "@types/oidc-provider") {
    fail(`expected @types/oidc-provider, found ${JSON.stringify(typesPackage.name)}`);
}
if (providerPackage.name !== "oidc-provider") {
    fail(`expected oidc-provider, found ${JSON.stringify(providerPackage.name)}`);
}

const typesVersion = majorMinor(typesPackage.version, "@types/oidc-provider");
const providerVersion = majorMinor(providerPackage.version, "oidc-provider");
if (typesVersion !== providerVersion) {
    fail(`version mismatch: @types/oidc-provider is ${typesVersion}.x but oidc-provider is ${providerVersion}.x`);
}
const providerSourceBase = `${providerPackage.homepage ?? "https://github.com/panva/node-oidc-provider"}/blob/main`;

const result = spawnSync(process.execPath, ["docs/update-configuration.js", "--configuration-json"], {
    cwd: providerDirectory,
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
});
if (result.error) {
    fail(`could not run the provider metadata generator: ${result.error.message}`);
}
if (result.status !== 0) {
    if (result.stderr) process.stderr.write(result.stderr);
    fail(`provider metadata generator exited with status ${result.status}`);
}

let payload;
try {
    payload = JSON.parse(result.stdout);
} catch (error) {
    fail(`provider metadata generator returned invalid JSON: ${error.message}`);
}

const entries = configurationEntries(payload);
const current = readFileSync(declarationPath, "utf8");
const withTypes = replaceGeneratedRegion(current, generatedRegion(entries));
validateTypeReferences(withTypes, entries);
const withDocumentation = replaceGeneratedDocumentation(withTypes, entries, providerSourceBase);
const updated = formatDeclaration(withDocumentation, packageDirectory, declarationPath);
if (current === updated) {
    console.log("Configuration documentation and option types are up to date.");
} else if (check) {
    fail("index.d.ts is not up to date; run the generator without --check");
} else {
    writeFileSync(declarationPath, updated);
    console.log("Updated configuration documentation and option types in index.d.ts.");
}
